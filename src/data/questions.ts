// Each question has the same 0–4 range. Safety decisions never reduce points.
function q(
  n: number,
  category: CategoryId,
  text: string,
  aside: string,
  options: [string, number][],
): Question {
  return {
    id: `q${n}`,
    category,
    text,
    aside,
    answers: options.map(([label, points], i) => ({ id: `a${i}`, label, points })),
  };
}

